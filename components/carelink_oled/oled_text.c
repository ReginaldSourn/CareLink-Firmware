static const uint8_t *glyph(char c)
{
    if (c >= 'a' && c <= 'z') c -= 'a' - 'A';
    for (size_t i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); ++i) {
        if (glyphs[i].symbol == c) return glyphs[i].columns;
    }
    return glyphs[sizeof(glyphs) / sizeof(glyphs[0]) - 1].columns;
}

void oled_text_render(uint8_t frame[OLED_FRAME_BYTES],
                      const char *const lines[], size_t count)
{
    memset(frame, 0, OLED_FRAME_BYTES);
    if (!lines) return;
    if (count > OLED_HEIGHT / 8) count = OLED_HEIGHT / 8;
    for (size_t row = 0; row < count; ++row) {
        if (!lines[row]) continue;
        for (size_t column = 0; column < OLED_WIDTH / 6 && lines[row][column]; ++column) {
            memcpy(frame + row * OLED_WIDTH + column * 6, glyph(lines[row][column]), 5);
        }
    }
}
